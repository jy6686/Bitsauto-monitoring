#!/usr/bin/env node
// Platform Feature Audit — BUSINESS inventory extractor (read-only).
// Canonical source = the Top Menu `DOMAINS` in app-nav-shell.tsx (business
// architecture): Domain → Capability (group) → Feature (item) → route.
// Cross-checks feature count against SIDEBAR_GROUPS (the Navigation Manager
// visibility registry) to surface Top-Menu-vs-visibility discrepancies.
//
// Usage: node extract-business.mjs [outFile]   (default: ../BUSINESS-INVENTORY.md)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '../../../..');           // repo root
const read = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');

const nav = read('client/src/components/app-nav-shell.tsx');
const shell = read('client/src/components/layout-shell.tsx');

// ── Parse DOMAINS (Top Menu) → domain → capability(group) → feature(item) ─────
const s = nav.indexOf('const DOMAINS');
const e = nav.indexOf('\n];', s);
const block = nav.slice(s, e);

const domains = [];
let dom = null, grp = null;
for (const line of block.split('\n')) {
  const dM = line.match(/^\s{2,4}id:\s*'([^']+)',\s*label:\s*'([^']+)'/);
  if (dM) { dom = { id: dM[1], label: dM[2], groups: [] }; domains.push(dom); grp = null; continue; }
  // group header: has `label:` + `items: [` but no `href:`
  const gM = line.match(/\{\s*label:\s*'([^']+)',/);
  if (gM && /items:\s*\[/.test(line) && !/href:/.test(line) && dom) {
    grp = { capability: gM[1], features: [] }; dom.groups.push(grp); continue;
  }
  const iM = line.match(/\{\s*href:\s*'([^']+)',\s*label:\s*'([^']+)'(?:,\s*desc:\s*'([^']*)')?/);
  if (iM && grp) grp.features.push({ route: iM[1], feature: iM[2], desc: iM[3] || '' });
}

const featureCount = domains.reduce((n, d) => n + d.groups.reduce((m, g) => m + g.features.length, 0), 0);

// ── Cross-check: SIDEBAR_GROUPS feature count (visibility registry) ───────────
const navHrefs = new Set([...shell.matchAll(/\{\s*href:\s*"([^"]+)"/g)].map(m => m[1]));
const domHrefs = new Set(domains.flatMap(d => d.groups.flatMap(g => g.features.map(f => f.route))));
const inDomNotNav = [...domHrefs].filter(h => !navHrefs.has(h)).sort();
const inNavNotDom = [...navHrefs].filter(h => !domHrefs.has(h)).sort();

// ── Emit ─────────────────────────────────────────────────────────────────────
let md = `# Business Inventory (canonical) \`[V @ app-nav-shell.tsx DOMAINS]\`

> Generated by \`tools/extract-business.mjs\` (read-only). Canonical source = the
> **Top Menu** \`DOMAINS\`. Hierarchy: Domain → Capability → Feature → route.
> **${domains.length} domains · ${featureCount} features.**

`;
for (const d of domains) {
  md += `## ${d.label} \`${d.id}\`\n\n| Capability | Feature | Route | Description |\n|---|---|---|---|\n`;
  for (const g of d.groups)
    for (const f of g.features)
      md += `| ${g.capability} | ${f.feature} | \`${f.route}\` | ${f.desc} |\n`;
  md += `\n`;
}

md += `## Cross-check vs Navigation Manager (SIDEBAR_GROUPS)\n\n`;
md += `- Top-Menu features: **${domHrefs.size}** · Navigation-Manager routes: **${navHrefs.size}**\n`;
md += `- In Top Menu but NOT in Navigation Manager (${inDomNotNav.length}): ${inDomNotNav.map(h => `\`${h}\``).join(' ') || '—'}\n`;
md += `- In Navigation Manager but NOT in Top Menu (${inNavNotDom.length}): ${inNavNotDom.map(h => `\`${h}\``).join(' ') || '—'}\n`;
md += `\n> The Business Inventory is authoritative; SIDEBAR_GROUPS differences are\n`;
md += `> visibility/registry discrepancies to reconcile, not architecture.\n`;

const out = process.argv[2] || path.join(HERE, '..', 'BUSINESS-INVENTORY.md');
fs.writeFileSync(out, md);
console.log(`Wrote ${out}: ${domains.length} domains, ${featureCount} features. ` +
  `Cross-check: +${inDomNotNav.length} top-only, +${inNavNotDom.length} nav-only.`);
